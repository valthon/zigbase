//! Pure-Zig TypeScript client generator executable.
//! Reads @import("app").App.collections and emits a zbase.gen.ts.
//! Pure functions (generate, schemaHash) use relative imports so they can be
//! reached by the library test suite without a circular zigbase reference.
//! main() is the only function that touches @import("zigbase")/@import("app") and IO.
const std = @import("std");
const schema = @import("../schema.zig");
const events = @import("../events.zig");
const features = @import("../features.zig");
const emit = @import("emit.zig");
const guards = @import("guards.zig");
const ident = @import("identifiers.zig");
const rpc_ts = @import("rpc_ts.zig");
const rpc = @import("rpc.zig");
const gen_dart = @import("gen_dart.zig");
const gen_python = @import("gen_python.zig");
const gen_kotlin = @import("gen_kotlin.zig");

const W = std.ArrayList(u8);

/// FNV-1a over a canonical serialization of the collections (declared order).
pub fn schemaHash(cols: []const schema.Collection) u64 {
    var h = std.hash.Fnv1a_64.init();
    for (cols) |c| {
        h.update(c.name);
        h.update("|");
        h.update(@tagName(c.type));
        for (c.fields) |f| {
            h.update("\x00");
            h.update(f.name);
            h.update(":");
            h.update(@tagName(std.meta.activeTag(f.options)));
            if (f.required) h.update("!");
            if (f.isMultiValue()) h.update("*");
            if (f.searchable) h.update("?");
            switch (f.options) {
                .select => |o| for (o.values) |v| {
                    h.update(",");
                    h.update(v);
                },
                .relation => |o| {
                    h.update("->");
                    h.update(o.targetCollectionId);
                },
                else => {},
            }
        }
        if (c.options.tenant_field) |tf| {
            h.update("\x01tenant:");
            h.update(tf);
        }
    }
    return h.final();
}

fn section(alloc: std.mem.Allocator, w: *W, title: []const u8) !void {
    const line = try std.fmt.allocPrint(alloc, "\n// ---- {s} " ++ ("-" ** 4) ++ "\n\n", .{title});
    try w.appendSlice(alloc, line);
}

/// The pure generator core: collections -> full file text. Runs guards first.
pub fn generate(
    alloc: std.mem.Allocator,
    cols: []const schema.Collection,
    comptime routes: []const events.RouteMeta,
    comptime custom_auth: []const events.CustomAuthMeta,
    // Declared feature-flag + experiment metadata (#130). Plain data (no `type`
    // fields), so these are runtime params; the runtime-introspection path passes
    // empty (`&.{}`), exactly the asymmetry of routes/custom_auth.
    flags: []const features.FlagDef,
    experiments: []const features.ExperimentDef,
    in_repo: bool,
    auth_collection: []const u8,
    client_name: []const u8,
    api_prefix: []const u8,
) ![]const u8 {
    // Validate that every route path starts with the given api_prefix.
    // Must use `inline for` because RouteMeta contains `Input: type` (comptime-only field).
    inline for (routes) |r| {
        if (!std.mem.startsWith(u8, r.path, api_prefix)) {
            std.log.err("gen_client: route '{s}' does not start with --api-prefix '{s}'; the framework route prefix and the generator prefix disagree.", .{ r.path, api_prefix });
            return error.RoutePrefixMismatch;
        }
    }

    var report = guards.GuardReport{ .message = "" };
    try guards.checkOperatorNames(alloc, cols, &report);
    try guards.checkIdentifiers(alloc, cols, &report);

    var w: W = .empty;
    // header
    try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "// generated by zigbase — do not edit\n// schema-hash: {x:0>16}\n//\n", .{schemaHash(cols)}));
    if (in_repo) {
        try w.appendSlice(alloc,
            \\// In a consumer repo this file imports from "@zigbase/client" and
            \\// "@zigbase/client/typed". In this in-repo snapshot we import from the
            \\// package source so it typechecks against the working tree without a built dist.
            \\
        );
    } else {
        try w.appendSlice(alloc,
            \\// This client imports its runtime and types from the "@zigbase/client"
            \\// and "@zigbase/client/typed" packages.
            \\
        );
    }
    // SendOptions is referenced by typed RPC routes AND by auth-method stubs
    // (built-in or custom), so import it whenever either is present.
    try emit.emitImports(alloc, &w, in_repo, routes.len > 0 or anyNonPasswordAuthMethods(cols));

    try section(alloc, &w, "Records");
    for (cols) |c| try emit.emitSelectUnions(alloc, &w, c);
    for (cols) |c| {
        try emit.emitRecord(alloc, &w, c);
        try w.appendSlice(alloc, "\n");
    }
    try section(alloc, &w, "Create / Update payloads");
    for (cols) |c| {
        try emit.emitCreate(alloc, &w, c);
        try emit.emitUpdate(alloc, &w, c);
    }
    try section(alloc, &w, "Where types");
    for (cols) |c| try emit.emitWhere(alloc, &w, cols, c);
    try section(alloc, &w, "Relations + expand keys");
    for (cols) |c| {
        try emit.emitRelations(alloc, &w, cols, c);
        try emit.emitExpandKeys(alloc, &w, cols, c);
    }
    try section(alloc, &w, "Fluent accessor types");
    for (cols) |c| {
        try emit.emitFields(alloc, &w, c);
        try emit.emitSortUnion(alloc, &w, c);
    }
    try section(alloc, &w, "Concrete service interfaces");
    for (cols) |c| try emit.emitService(alloc, &w, c);
    try section(alloc, &w, "Per-collection metadata");
    for (cols) |c| try emit.emitMeta(alloc, &w, c);
    try emit.emitRelationResolver(alloc, &w, cols);
    try section(alloc, &w, "Typed files surface");
    try emit.emitTypedFiles(alloc, &w, cols);
    try section(alloc, &w, "Typed realtime surface");
    for (cols) |c| try emit.emitRealtimeAlias(alloc, &w, c);
    try section(alloc, &w, "createClient");
    // One SeenMap shared across the typed RPC route surface AND the typed custom-auth
    // surface, so two DISTINCT Zig types that map to the same TS name across those
    // surfaces are caught (error.RpcTypeNameCollision) instead of emitting an
    // ambiguous client (Decision E).
    var seen = rpc_ts.SeenMap.init(alloc);
    defer seen.deinit();
    const rpc_section = try rpc.renderShared(routes, alloc, &seen);
    // rpc_section slices are owned by the arena (alloc), freed on arena deinit.
    try emitClientFactory(alloc, &w, cols, client_name, auth_collection, rpc_section, routes.len, api_prefix, custom_auth, &seen, flags, experiments);

    return w.toOwnedSlice(alloc);
}

/// The createClient + client-interface block (mirrors blog.gen.ts createClient).
fn emitClientFactory(
    alloc: std.mem.Allocator,
    w: *W,
    cols: []const schema.Collection,
    client_name: []const u8,
    auth_collection: []const u8,
    rpc_section: rpc.Section,
    routes_len: usize,
    api_prefix: []const u8,
    comptime custom_auth: []const events.CustomAuthMeta,
    seen: *rpc_ts.SeenMap,
    flags: []const features.FlagDef,
    experiments: []const features.ExperimentDef,
) !void {
    // The typed feature-state surface (`zb.flags.resolveAll`) is emitted only when the
    // app declares at least one flag or experiment (otherwise the snapshot is unchanged).
    const has_features = flags.len > 0 or experiments.len > 0;
    // Pre-build the auth iface + factory sections (empty if no non-password methods).
    // `auth_decls` receives the named `export interface`/`export type` declarations for
    // any TYPED custom auth methods (deduped through the shared `seen` map).
    var auth_iface: W = .empty;
    var auth_factory: W = .empty;
    var auth_decls: W = .empty;
    try emitAuthMethodEndpoints(alloc, &auth_iface, &auth_factory, &auth_decls, cols, api_prefix, custom_auth, seen);
    const auth_iface_s = try auth_iface.toOwnedSlice(alloc);
    const auth_factory_s = try auth_factory.toOwnedSlice(alloc);
    const auth_decls_s = try auth_decls.toOwnedSlice(alloc);
    const has_auth_methods = auth_iface_s.len > 0;

    // Emit named RPC Input/Output decls before the client interface (only when routes exist).
    if (routes_len > 0) {
        try w.appendSlice(alloc, rpc_section.decls);
    }
    // Emit the shared built-in auth-method I/O interfaces before the client interface
    // (only for built-ins actually enabled across the collections).
    if (has_auth_methods) try emitAuthMethodIODecls(alloc, w, cols);
    // Emit named decls for any TYPED custom auth methods (after built-ins, still before
    // the client interface that references them).
    if (auth_decls_s.len > 0) {
        try section(alloc, w, "Custom auth method I/O");
        try w.appendSlice(alloc, auth_decls_s);
    }
    // Named FeatureState type for the public `zb.flags.resolveAll` surface (#130):
    // flags as named booleans, experiments as string-literal unions of their variants.
    if (has_features) {
        try section(alloc, w, "Feature state");
        try emitFeatureState(alloc, w, flags, experiments);
    }
    // BlogClient-style interface
    try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "export interface {s} {{\n  db: {{\n", .{client_name}));
    for (cols) |c| try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "    {s}: {s};\n", .{ c.name, try ident.serviceName(alloc, c.name) }));
    try w.appendSlice(alloc, "  };\n  realtime: {\n");
    for (cols) |c| try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "    {s}: {s};\n", .{ c.name, try ident.realtimeAliasName(alloc, c.name) }));
    // auth method stubs (non-password methods only; password stays on db.<col>.authWithPassword)
    try w.appendSlice(alloc, "  };\n");
    if (has_auth_methods) try w.appendSlice(alloc, auth_iface_s);
    if (has_features) try w.appendSlice(alloc,
        \\  flags: {
        \\    resolveAll(subject: string): Promise<FeatureState>;
        \\  };
        \\
    );
    if (routes_len > 0) {
        try w.appendSlice(alloc,
            \\  files: FilesService;
        );
        try w.appendSlice(alloc, "\n  rpc: {\n");
        try w.appendSlice(alloc, rpc_section.iface_member);
        try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
            \\  }};
            \\  accounts: Client["accounts"];
            \\  analytics: Client["analytics"];
            \\  senders: Client["senders"];
            \\  withAccount(accountId: string): {0s};
            \\  authStore: Client["authStore"];
            \\  send: Client["send"];
            \\  fetch: Client["fetch"];
            \\}}
            \\
        , .{client_name}));
    } else {
        try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
            \\  files: FilesService;
            \\  accounts: Client["accounts"];
            \\  analytics: Client["analytics"];
            \\  senders: Client["senders"];
            \\  withAccount(accountId: string): {0s};
            \\  authStore: Client["authStore"];
            \\  send: Client["send"];
            \\  fetch: Client["fetch"];
            \\}}
            \\
        , .{client_name}));
    }
    // options interface
    try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
        \\export interface {s}Options {{
        \\  fetch?: typeof fetch;
        \\  WebSocket?: typeof WebSocket;
        \\  authCollection?: string;
        \\}}
        \\
    , .{client_name}));
    // createClient
    try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
        \\export function createClient(url: string, opts: {0s}Options = {{}}): {0s} {{
        \\  const base: RealtimeEnabledClient = withRealtime(
        \\    baseCreateClient(url, {{
        \\      fetch: opts.fetch,
        \\      WebSocket: opts.WebSocket,
        \\      authCollection: opts.authCollection ?? "{1s}",
        \\    }}),
        \\  );
        \\  return makeClient(base);
        \\}}
        \\
        \\/** Build the typed facade over a realtime-enabled base client. All facades are
        \\ *  stateless wrappers, so `withAccount` can rebuild them cheaply per scope. */
        \\function makeClient(base: RealtimeEnabledClient): {0s} {{
        \\  return {{
        \\    db: {{
        \\
    , .{ client_name, auth_collection }));
    for (cols) |c| {
        const mc = try ident.metaConst(alloc, c.name);
        const svc = try ident.serviceName(alloc, c.name);
        const resolver = if (emit_hasRelations(c)) ", relationResolver" else "";
        const file_fields = emit_hasSingleFileFields(c);
        if (c.type == .auth and file_fields) {
            // Auth collection WITH file fields: Object.assign with both authWithPassword + fileUrl.
            try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
                \\      {0s}: Object.assign(
                \\        makeRecordService(base, {1s}{2s}) as unknown as {3s},
                \\        {{
                \\          authWithPassword: (identity: string, password: string) =>
                \\            base.collection("{0s}").authWithPassword(identity, password),
                \\          fileUrl: (record: any, field: any, opts: any) =>
                \\            base.files.getUrl({{ id: record.id, collectionName: "{0s}" }}, (record as Record<string, string>)[field] ?? "", opts),
                \\        }},
                \\      ) as unknown as {3s},
                \\
            , .{ c.name, mc, resolver, svc }));
        } else if (c.type == .auth) {
            try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
                \\      {0s}: Object.assign(
                \\        makeRecordService(base, {1s}{2s}) as unknown as {3s},
                \\        {{
                \\          authWithPassword: (identity: string, password: string) =>
                \\            base.collection("{0s}").authWithPassword(identity, password),
                \\        }},
                \\      ) as unknown as {3s},
                \\
            , .{ c.name, mc, resolver, svc }));
        } else if (file_fields) {
            // Non-auth collection WITH file fields: Object.assign to graft fileUrl.
            try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
                \\      {0s}: Object.assign(
                \\        makeRecordService(base, {1s}{2s}) as unknown as {3s},
                \\        {{
                \\          fileUrl: (record: any, field: any, opts: any) =>
                \\            base.files.getUrl({{ id: record.id, collectionName: "{0s}" }}, (record as Record<string, string>)[field] ?? "", opts),
                \\        }},
                \\      ) as unknown as {3s},
                \\
            , .{ c.name, mc, resolver, svc }));
        } else {
            try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "      {0s}: makeRecordService(base, {1s}{2s}) as unknown as {3s},\n", .{ c.name, mc, resolver, svc }));
        }
    }
    try w.appendSlice(alloc, "    },\n    realtime: {\n");
    for (cols) |c| {
        const rec = try ident.recordName(alloc, c.name);
        const wn = try ident.whereName(alloc, c.name);
        const mc = try ident.metaConst(alloc, c.name);
        const resolver = if (emit_hasRelations(c)) ", relationResolver" else "";
        try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "      {0s}: makeTypedRealtime<{1s}, {2s}>(base.realtime, {3s}{4s}),\n", .{ c.name, rec, wn, mc, resolver }));
    }
    // auth method stubs in the factory (non-password methods only)
    if (has_auth_methods) {
        try w.appendSlice(alloc, "    },\n");
        try w.appendSlice(alloc, auth_factory_s);
    } else {
        try w.appendSlice(alloc, "    },\n");
    }
    // Typed feature-state surface (#130): GET <prefix>/state?subject=<id>.
    if (has_features) {
        try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
            \\    flags: {{
            \\      resolveAll: (subject: string): Promise<FeatureState> =>
            \\        base.send<FeatureState>("GET", `{s}/state?subject=${{encodeURIComponent(subject)}}`),
            \\    }},
            \\
        , .{api_prefix}));
    }
    try w.appendSlice(alloc, "    files: base.files,\n");
    if (routes_len > 0) {
        try w.appendSlice(alloc, "    rpc: {\n");
        try w.appendSlice(alloc, rpc_section.factory_member);
        try w.appendSlice(alloc, "    },\n");
    }
    try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
        \\    accounts: base.accounts,
        \\    analytics: base.analytics,
        \\    senders: base.senders,
        \\    withAccount: (accountId: string): {0s} => makeClient(withRealtime(base.withAccount(accountId))),
        \\    authStore: base.authStore,
        \\    send: base.send.bind(base),
        \\    fetch: base.fetch.bind(base),
        \\  }};
        \\}}
        \\
    , .{client_name}));
}

/// Emit `export interface FeatureState { … }` for the public `zb.flags.resolveAll`
/// surface (#130): each declared flag is a named `boolean`; each experiment is a
/// string-literal union of its declared variants. Empty groups map to
/// `Record<string, never>` (the precise empty-object type the server returns).
/// Flag/experiment names are Zig identifiers, so they need no quoting.
fn emitFeatureState(
    alloc: std.mem.Allocator,
    w: *W,
    flags: []const features.FlagDef,
    experiments: []const features.ExperimentDef,
) !void {
    try w.appendSlice(alloc, "export interface FeatureState {\n");
    if (flags.len == 0) {
        try w.appendSlice(alloc, "  flags: Record<string, never>;\n");
    } else {
        try w.appendSlice(alloc, "  flags: {\n");
        for (flags) |f| try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "    {s}: boolean;\n", .{f.name}));
        try w.appendSlice(alloc, "  };\n");
    }
    if (experiments.len == 0) {
        try w.appendSlice(alloc, "  experiments: Record<string, never>;\n");
    } else {
        try w.appendSlice(alloc, "  experiments: {\n");
        for (experiments) |e| {
            try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "    {s}: ", .{e.name}));
            for (e.variants, 0..) |v, i| {
                if (i > 0) try w.appendSlice(alloc, " | ");
                try w.appendSlice(alloc, try std.fmt.allocPrint(alloc, "\"{s}\"", .{v}));
            }
            try w.appendSlice(alloc, ";\n");
        }
        try w.appendSlice(alloc, "  };\n");
    }
    try w.appendSlice(alloc, "}\n");
}

fn emit_hasRelations(c: schema.Collection) bool {
    for (c.fields) |f| if (f.options == .relation) return true;
    return false;
}

/// Convert a snake_case slug (e.g. "magic_link") to camelCase (e.g. "magicLink").
/// First character is lowercased; underscores become word boundaries.
fn camelFromSlug(alloc: std.mem.Allocator, slug: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var upper_next = false;
    var first = true;
    for (slug) |ch| {
        if (ch == '_' or ch == '-') {
            upper_next = true;
            continue;
        }
        if (upper_next) {
            try out.append(alloc, std.ascii.toUpper(ch));
            upper_next = false;
        } else if (first) {
            try out.append(alloc, std.ascii.toLower(ch));
        } else {
            try out.append(alloc, ch);
        }
        first = false;
    }
    return out.toOwnedSlice(alloc);
}

/// Returns true if the collection has any non-password auth methods enabled.
fn hasNonPasswordAuthMethods(c: schema.Collection) bool {
    if (c.type != .auth) return false;
    const m = c.options.auth.methods;
    return m.magic_link != null or m.otp != null or m.webauthn != null or m.custom.len > 0;
}

/// Returns true if any collection in the slice has non-password auth methods.
fn anyNonPasswordAuthMethods(cols: []const schema.Collection) bool {
    for (cols) |c| if (hasNonPasswordAuthMethods(c)) return true;
    return false;
}

/// Typed I/O descriptor for a built-in auth method. The three built-ins
/// (magic_link, otp, webauthn) have FIXED server-side request/response contracts
/// (see src/auth/methods/*.zig + src/api/auth_methods.zig), so the generator can
/// emit precise TS types. Custom methods (m.custom slugs) carry no type info and
/// stay on the untyped `Record<string, unknown>`/`unknown` stubs (see below).
const BuiltinIO = struct {
    /// camelCase accessor name on `client.auth.<col>.<camel>`.
    camel: []const u8,
    /// TS type of the `initiate` input body.
    init_input: []const u8,
    /// TS type the `initiate` promise resolves to.
    init_result: []const u8,
    /// TS type of the `complete` input body.
    complete_input: []const u8,
    /// TS type the `complete` promise resolves to.
    complete_result: []const u8,
};

/// Map a built-in slug to its typed I/O contract. Returns null for custom slugs.
///
/// Contracts derived directly from the handlers:
///   - magic_link: initiate reads {identity} → 204 (void); complete reads {token}
///     → 200 {token} (src/auth/methods/magic_link.zig).
///   - otp: initiate reads {identity} → 204 (void); complete reads {identity, code}
///     → 200 {token} (src/auth/methods/otp.zig).
///   - webauthn: initiate reads optional {identity} → 200
///     {challenge, rpId, ceremonyId, timeout}; complete reads
///     {ceremonyId, credentialId, authenticatorData, clientDataJSON, signature}
///     → 200 {token} (src/auth/methods/webauthn.zig).
/// All three `complete` paths return `{token}` (AuthMethodResult) — the session is
/// also set via cookies by src/api/auth_methods.zig's dispatch().
fn builtinIO(slug: []const u8) ?BuiltinIO {
    if (std.mem.eql(u8, slug, "magic_link")) return .{
        .camel = "magicLink",
        .init_input = "MagicLinkInitiateInput",
        .init_result = "void",
        .complete_input = "MagicLinkCompleteInput",
        .complete_result = "AuthMethodResult",
    };
    if (std.mem.eql(u8, slug, "otp")) return .{
        .camel = "otp",
        .init_input = "OtpInitiateInput",
        .init_result = "void",
        .complete_input = "OtpCompleteInput",
        .complete_result = "AuthMethodResult",
    };
    if (std.mem.eql(u8, slug, "webauthn")) return .{
        .camel = "webauthn",
        .init_input = "WebAuthnInitiateInput",
        .init_result = "WebAuthnInitiateResult",
        .complete_input = "WebAuthnCompleteInput",
        .complete_result = "AuthMethodResult",
    };
    return null;
}

/// Emit the shared TS interfaces for the built-in auth-method I/O contracts that
/// are actually enabled across `cols`. These are global (the contract is the same
/// regardless of which collection enables the method), so they are emitted once,
/// just before the client interface. `AuthMethodResult` is shared by every
/// built-in `complete`.
fn emitAuthMethodIODecls(alloc: std.mem.Allocator, w: *W, cols: []const schema.Collection) !void {
    var any_ml = false;
    var any_otp = false;
    var any_wa = false;
    for (cols) |c| {
        if (c.type != .auth) continue;
        const m = c.options.auth.methods;
        if (m.magic_link != null) any_ml = true;
        if (m.otp != null) any_otp = true;
        if (m.webauthn != null) any_wa = true;
    }
    if (!any_ml and !any_otp and !any_wa) return;

    try section(alloc, w, "Built-in auth method I/O");
    // Shared success result for every built-in `complete` (the session is also set
    // via zb_auth/zb_csrf cookies on the response).
    try w.appendSlice(alloc,
        \\export interface AuthMethodResult {
        \\  /** Session JWT. Session cookies (zb_auth/zb_csrf) are also set on the response. */
        \\  token: string;
        \\}
        \\
    );
    if (any_ml) try w.appendSlice(alloc,
        \\export interface MagicLinkInitiateInput {
        \\  /** Email/identity to send the single-use sign-in link to. */
        \\  identity: string;
        \\}
        \\export interface MagicLinkCompleteInput {
        \\  /** The single-use link token delivered by email. */
        \\  token: string;
        \\}
        \\
    );
    if (any_otp) try w.appendSlice(alloc,
        \\export interface OtpInitiateInput {
        \\  /** Email/identity to send the one-time code to. */
        \\  identity: string;
        \\}
        \\export interface OtpCompleteInput {
        \\  identity: string;
        \\  /** The one-time numeric code delivered by email. */
        \\  code: string;
        \\}
        \\
    );
    if (any_wa) try w.appendSlice(alloc,
        \\export interface WebAuthnInitiateInput {
        \\  /** Optional identity; omit for a usernameless (discoverable) login. */
        \\  identity?: string;
        \\}
        \\export interface WebAuthnInitiateResult {
        \\  /** base64url-encoded random challenge to sign. */
        \\  challenge: string;
        \\  rpId: string;
        \\  /** Opaque id correlating this initiate with the matching complete. */
        \\  ceremonyId: string;

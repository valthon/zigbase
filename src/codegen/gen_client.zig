    // An auth collection with magic_link enabled.
    const members_cols = try a.dupe(schema.Collection, &.{
        .{
            .id = "",
            .name = "members",
            .type = .auth,
            .fields = &.{},
            .options = .{ .auth = .{ .methods = .{ .magic_link = .{} } } },
        },
    });
    const out_ml = try generate(a, members_cols, &.{}, true, "members", "MembersClient", "/api");

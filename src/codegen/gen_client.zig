/// Emit the `auth` surface for non-password auth methods into both the interface
/// and factory sections.
/// Naming: client.auth.<colName>.<methodCamelCase>.initiate / .complete
/// Posts to /api/collections/<col>/auth/<slug>/initiate|complete.
/// Built-in methods (magic_link/otp/webauthn) get precise typed I/O (see
/// builtinIO + emitAuthMethodIODecls); custom slugs keep the untyped stubs.
fn emitAuthMethodEndpoints(
    alloc: std.mem.Allocator,
    w_iface: *W, // receives the auth: { ... } interface body
    w_factory: *W, // receives the auth: { ... } factory body
    w_decls: *W, // receives named decls for TYPED custom methods
    cols: []const schema.Collection,
    api_prefix: []const u8,
    comptime custom_auth: []const events.CustomAuthMeta,
    seen: *rpc_ts.SeenMap,
) !void {
    // Build the list of (colName, []slug) pairs for non-password methods.
    // We need a helper to iterate slugs for a given MethodsOptions.
    //
    // Only emit if there is at least one collection with non-password methods.
    if (!anyNonPasswordAuthMethods(cols)) return;

    // Interface: auth: {
    try w_iface.appendSlice(alloc,
        \\  auth: {
        \\
    );
    // Factory: auth: {
    try w_factory.appendSlice(alloc,
        \\    auth: {
        \\
    );

    for (cols) |c| {
        if (!hasNonPasswordAuthMethods(c)) continue;

        // Interface: <colName>: {
        try w_iface.appendSlice(alloc, try std.fmt.allocPrint(alloc, "    {s}: {{\n", .{c.name}));
        // Factory: <colName>: {
        try w_factory.appendSlice(alloc, try std.fmt.allocPrint(alloc, "      {s}: {{\n", .{c.name}));

        // Collect slugs of enabled non-password methods.
        const m = c.options.auth.methods;

        // Helper: emit TYPED interface + factory lines for one built-in slug.
        const emit_builtin = struct {
            fn emit(
                a: std.mem.Allocator,
                wi: *W,
                wf: *W,
                col_name: []const u8,
                slug: []const u8,
                prefix: []const u8,
                io: BuiltinIO,
            ) !void {
                // Interface member
                try wi.appendSlice(a, try std.fmt.allocPrint(a,
                    \\      {0s}: {{
                    \\        initiate(input: {1s}, opts?: SendOptions): Promise<{2s}>;
                    \\        complete(input: {3s}, opts?: SendOptions): Promise<{4s}>;
                    \\      }};
                    \\
                , .{ io.camel, io.init_input, io.init_result, io.complete_input, io.complete_result }));
                // Factory member — explicit send<T> type args so the object literal
                // is assignable to the typed interface above.
                try wf.appendSlice(a, try std.fmt.allocPrint(a,
                    \\        {0s}: {{
                    \\          initiate: (input: {4s}, opts?: SendOptions): Promise<{5s}> =>
                    \\            base.send<{5s}>("POST", `{1s}/collections/{2s}/auth/{3s}/initiate`, {{ body: input, ...opts }}),
                    \\          complete: (input: {6s}, opts?: SendOptions): Promise<{7s}> =>
                    \\            base.send<{7s}>("POST", `{1s}/collections/{2s}/auth/{3s}/complete`, {{ body: input, ...opts }}),
                    \\        }},
                    \\
                , .{ io.camel, prefix, col_name, slug, io.init_input, io.init_result, io.complete_input, io.complete_result }));
            }
        }.emit;

        // Helper: emit UNTYPED interface + factory lines for one custom slug.
        const emit_custom = struct {
            fn emit(
                a: std.mem.Allocator,
                wi: *W,
                wf: *W,
                col_name: []const u8,
                slug: []const u8,
                prefix: []const u8,
            ) !void {
                const camel_name = try camelFromSlug(a, slug);
                // Interface member
                try wi.appendSlice(a, try std.fmt.allocPrint(a,
                    \\      {0s}: {{
                    \\        // TODO(typed): custom auth methods carry no type info (m.custom is bare
                    \\        // slug strings). Typing these needs a comptime typed-I/O declaration API
                    \\        // — m.custom entries carrying comptime Input/Output Zig types the generator
                    \\        // can reflect. Until then these stay untyped.
                    \\        initiate(input: Record<string, unknown>, opts?: SendOptions): Promise<unknown>;
                    \\        complete(input: Record<string, unknown>, opts?: SendOptions): Promise<unknown>;
                    \\      }};
                    \\
                , .{camel_name}));
                // Factory member
                try wf.appendSlice(a, try std.fmt.allocPrint(a,
                    \\        {0s}: {{
                    \\          initiate: (input: Record<string, unknown>, opts?: SendOptions) =>
                    \\            base.send("POST", `{1s}/collections/{2s}/auth/{3s}/initiate`, {{ body: input, ...opts }}),
                    \\          complete: (input: Record<string, unknown>, opts?: SendOptions) =>
                    \\            base.send("POST", `{1s}/collections/{2s}/auth/{3s}/complete`, {{ body: input, ...opts }}),
                    \\        }},
                    \\
                , .{ camel_name, prefix, col_name, slug }));
            }
        }.emit;

        if (m.magic_link != null) try emit_builtin(alloc, w_iface, w_factory, c.name, "magic_link", api_prefix, builtinIO("magic_link").?);
        if (m.otp != null) try emit_builtin(alloc, w_iface, w_factory, c.name, "otp", api_prefix, builtinIO("otp").?);
        if (m.webauthn != null) try emit_builtin(alloc, w_iface, w_factory, c.name, "webauthn", api_prefix, builtinIO("webauthn").?);
        for (m.custom) |slug| {
            // A custom slug declared with comptime I/O types (a struct entry in the
            // `.custom` tuple) gets a TYPED surface; a bare-string slug stays untyped.
            var matched = false;
            inline for (custom_auth) |cm| {
                if (!matched and std.mem.eql(u8, cm.col_name, c.name) and std.mem.eql(u8, cm.slug, slug)) {
                    try emitCustomTyped(alloc, w_iface, w_factory, w_decls, seen, c.name, slug, cm, api_prefix);
                    matched = true;
                }
            }
            if (!matched) try emit_custom(alloc, w_iface, w_factory, c.name, slug, api_prefix);
        }

        // Interface: close colName
        try w_iface.appendSlice(alloc, "    };\n");
        // Factory: close colName
        try w_factory.appendSlice(alloc, "      },\n");
    }

    // Interface: close auth
    try w_iface.appendSlice(alloc, "  };\n");
    // Factory: close auth
    try w_factory.appendSlice(alloc, "    },\n");
}

/// Emit the TYPED interface + factory + named-decls for one custom auth method whose
/// comptime I/O types were declared via the `.custom` struct form. Mirrors the
/// built-in path (`emit_builtin` + `emitAuthMethodIODecls`) but reflects the declared
/// Zig types through `rpc_ts` (interfaces named by the Zig type's own short name).
/// A `void` Input omits the `input` argument; a `void` Output maps to `Promise<void>`
/// (Decision C). Named decls are deduped through the shared `seen` map (Decision E).
fn emitCustomTyped(
    a: std.mem.Allocator,
    wi: *W,
    wf: *W,
    wd: *W,
    seen: *rpc_ts.SeenMap,
    col_name: []const u8,
    slug: []const u8,
    comptime cm: events.CustomAuthMeta,
    prefix: []const u8,
) !void {
    const camel = try camelFromSlug(a, slug);

    // Named `export interface`/`export type` decls for each non-scalar I/O type,
    // dependencies first, deduped (and collision-checked) via the shared seen map.
    try rpc_ts.renderNamedDeclsShared(cm.InitiateInput, wd, a, seen);
    try rpc_ts.renderNamedDeclsShared(cm.InitiateOutput, wd, a, seen);
    try rpc_ts.renderNamedDeclsShared(cm.CompleteInput, wd, a, seen);
    try rpc_ts.renderNamedDeclsShared(cm.CompleteOutput, wd, a, seen);

    const init_in = comptime rpc_ts.tsForType(cm.InitiateInput);
    const init_out = comptime rpc_ts.tsForType(cm.InitiateOutput);
    const comp_in = comptime rpc_ts.tsForType(cm.CompleteInput);
    const comp_out = comptime rpc_ts.tsForType(cm.CompleteOutput);
    const init_has_input = cm.InitiateInput != void;
    const comp_has_input = cm.CompleteInput != void;

    // Interface member: <camel>: { initiate(...): Promise<...>; complete(...): Promise<...>; };
    try wi.appendSlice(a, try std.fmt.allocPrint(a, "      {s}: {{\n", .{camel}));
    if (init_has_input) {
        try wi.appendSlice(a, try std.fmt.allocPrint(a, "        initiate(input: {s}, opts?: SendOptions): Promise<{s}>;\n", .{ init_in, init_out }));
    } else {
        try wi.appendSlice(a, try std.fmt.allocPrint(a, "        initiate(opts?: SendOptions): Promise<{s}>;\n", .{init_out}));
    }
    if (comp_has_input) {
        try wi.appendSlice(a, try std.fmt.allocPrint(a, "        complete(input: {s}, opts?: SendOptions): Promise<{s}>;\n", .{ comp_in, comp_out }));
    } else {
        try wi.appendSlice(a, try std.fmt.allocPrint(a, "        complete(opts?: SendOptions): Promise<{s}>;\n", .{comp_out}));
    }
    try wi.appendSlice(a, "      };\n");

    // Factory member — explicit send<T> type arg so the literal is assignable to the iface.
    try wf.appendSlice(a, try std.fmt.allocPrint(a, "        {s}: {{\n", .{camel}));
    if (init_has_input) {
        try wf.appendSlice(a, try std.fmt.allocPrint(a,
            \\          initiate: (input: {0s}, opts?: SendOptions): Promise<{1s}> =>
            \\            base.send<{1s}>("POST", `{2s}/collections/{3s}/auth/{4s}/initiate`, {{ body: input, ...opts }}),
            \\
        , .{ init_in, init_out, prefix, col_name, slug }));
    } else {
        try wf.appendSlice(a, try std.fmt.allocPrint(a,
            \\          initiate: (opts?: SendOptions): Promise<{0s}> =>
            \\            base.send<{0s}>("POST", `{1s}/collections/{2s}/auth/{3s}/initiate`, {{ ...opts }}),
            \\
        , .{ init_out, prefix, col_name, slug }));
    }
    if (comp_has_input) {
        try wf.appendSlice(a, try std.fmt.allocPrint(a,
            \\          complete: (input: {0s}, opts?: SendOptions): Promise<{1s}> =>
            \\            base.send<{1s}>("POST", `{2s}/collections/{3s}/auth/{4s}/complete`, {{ body: input, ...opts }}),
            \\
        , .{ comp_in, comp_out, prefix, col_name, slug }));
    } else {
        try wf.appendSlice(a, try std.fmt.allocPrint(a,
            \\          complete: (opts?: SendOptions): Promise<{0s}> =>
            \\            base.send<{0s}>("POST", `{1s}/collections/{2s}/auth/{3s}/complete`, {{ ...opts }}),
            \\
        , .{ comp_out, prefix, col_name, slug }));
    }
    try wf.appendSlice(a, "        },\n");
}

/// Mirror of emit.zig's hasSingleFileFields: the per-collection fileUrl graft is
/// only valid for single-value file fields (a multi-value file field is string[]
/// on the record and can't be passed as a single filename). Collections whose only
/// file fields are multi-value fall through to the plain makeRecordService path.
fn emit_hasSingleFileFields(c: schema.Collection) bool {
    const tt = @import("ts_type.zig");
    for (c.fields) |f| if (tt.kindOf(f) == .file_name and !f.isMultiValue()) return true;
    return false;
}

const Args = struct {
    out: ?[]const u8 = null,
    api_prefix: []const u8 = "/api",
    check: bool = false,
    /// Output language: "ts" (default) or "dart".
    lang: []const u8 = "ts",
    /// Kotlin-only: the `package` declaration emitted at the top of the generated
    /// file. Mirrors `typegen --package`. Defaults to the dating fixture's
    /// namespace so the committed golden and `zig build gen-dating-kotlin-client`
    /// stay byte-stable; a consumer's gen-client step passes `--package
    /// your.app` to target its own namespace instead of the unoverridable
    /// hardcode this used to bake in.
    kotlin_package: []const u8 = "io.github.valthon.zigbase.codegen.dating",
};

/// Parse CLI args from the Zig 0.16 argv slice ([]const [:0]const u8).
fn parseArgsSlice(alloc: std.mem.Allocator, argv: []const [:0]const u8) !Args {
    var args = Args{};
    var i: usize = 1; // skip exe name
    while (i < argv.len) : (i += 1) {
        const a = argv[i];
        if (std.mem.eql(u8, a, "--out")) {
            i += 1;
            if (i >= argv.len) return error.MissingOutValue;
            args.out = try alloc.dupe(u8, argv[i]);
        } else if (std.mem.eql(u8, a, "--api-prefix")) {
            i += 1;
            if (i >= argv.len) return error.MissingApiPrefixValue;
            args.api_prefix = try alloc.dupe(u8, argv[i]);
        } else if (std.mem.eql(u8, a, "--check")) {
            args.check = true;
        } else if (std.mem.eql(u8, a, "--lang")) {
            i += 1;
            if (i >= argv.len) return error.MissingLangValue;
            args.lang = try alloc.dupe(u8, argv[i]);
        } else if (std.mem.eql(u8, a, "--package")) {
            i += 1;
            if (i >= argv.len) return error.MissingPackageValue;
            args.kotlin_package = try alloc.dupe(u8, argv[i]);
        } else {
            std.log.warn("gen_client: ignoring unknown arg '{s}'", .{a});
        }
    }
    return args;
}

/// Pick the auth collection name (first auth collection).
fn authCollectionName(cols: []const schema.Collection) []const u8 {
    for (cols) |c| if (c.type == .auth) return c.name;
    return "";
}

/// Entry point: Zig 0.16 `pub fn main(init: std.process.Init) !void`.
/// Threads `init.io` (for file operations) and uses `init.gpa` for a local arena,
/// reads argv from `init.minimal.args.toSlice(arena)` (yields `[]const [:0]const u8`).
/// Reads the ZBASE_INREPO env flag via `init.environ_map` (Zig 0.16's pure-Zig env
/// access through `std.process.Environ.Map` — no `std.c.getenv`, so this code adds no
/// libc dependency of its own).
///
/// NOTE (Task 7): In Zig 0.16, a file can only belong to one module. gen_client.zig
/// uses relative imports (@import("../schema.zig") etc.) which claim those files for
/// THIS module. If gen_client.zig is used as the exe module root AND zigbase is in
/// the dependency graph (via the `app` module), those files would be double-claimed.
/// The solution: use gen_main.zig as the exe root (which imports "zigbase" and "app"
/// as named modules) and call mainWithCollections() here. This keeps gen_client.zig
/// as a self-contained library file usable by the zigbase test suite WITHOUT being
/// a module root.
pub fn mainWithCollections(init: std.process.Init, cols: []const schema.Collection, comptime routes: []const events.RouteMeta, comptime custom_auth: []const events.CustomAuthMeta, flags: []const features.FlagDef, experiments: []const features.ExperimentDef) !void {
    const io = init.io;
    // Use an arena for all temporary allocations during the generator run.
    var arena_state = std.heap.ArenaAllocator.init(init.gpa);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    // argv: []const [:0]const u8 (Zig 0.16 — init.minimal.args.toSlice returns this).
    const argv = try init.minimal.args.toSlice(a);
    const args = try parseArgsSlice(a, argv);
    const out_path = args.out orelse {
        std.log.err("gen_client: --out <path> is required", .{});
        return error.MissingOut;
    };

    // ZBASE_INREPO: read via init.environ_map (Zig 0.16 pure-Zig env access; no libc).
    // contains() means the var is set (value may be empty string — that's fine).
    const in_repo = init.environ_map.contains("ZBASE_INREPO");
    const client_name = "ZbClient";
    const want_dart = std.mem.eql(u8, args.lang, "dart");
    const want_python = std.mem.eql(u8, args.lang, "python");
    const want_kotlin = std.mem.eql(u8, args.lang, "kotlin");
    if (!want_dart and !want_python and !want_kotlin and !std.mem.eql(u8, args.lang, "ts")) {
        std.log.err("gen_client: unknown --lang '{s}' (expected 'ts', 'dart', 'python', or 'kotlin')", .{args.lang});
        return error.BadLang;
    }

    const text = (if (want_dart)
        gen_dart.generate(a, cols, routes, custom_auth, flags, experiments, in_repo, authCollectionName(cols), client_name, args.api_prefix)
    else if (want_python)
        gen_python.generate(a, cols, routes, custom_auth, flags, experiments, in_repo, authCollectionName(cols), client_name, args.api_prefix)
    else if (want_kotlin)
        gen_kotlin.generate(a, cols, routes, custom_auth, flags, experiments, in_repo, authCollectionName(cols), client_name, args.api_prefix, args.kotlin_package)
    else
        generate(a, cols, routes, custom_auth, flags, experiments, in_repo, authCollectionName(cols), client_name, args.api_prefix)) catch |e| {
        // guard messages are printed via the report; re-run path for the message:
        var report = guards.GuardReport{ .message = "" };
        guards.checkOperatorNames(a, cols, &report) catch {};
        guards.checkIdentifiers(a, cols, &report) catch {};
        if (report.message.len > 0) std.log.err("{s}", .{report.message});
        return e;
    };

    if (args.check) {
        // Zig 0.16 file-read: std.Io.Dir.cwd().readFileAlloc(io, path, alloc, .limited(N))
        const existing = std.Io.Dir.cwd().readFileAlloc(io, out_path, a, .limited(64 * 1024 * 1024)) catch |e| {
            std.log.err("gen_client --check: cannot read '{s}': {s}", .{ out_path, @errorName(e) });
            return error.CheckReadFailed;
        };
        if (!std.mem.eql(u8, existing, text)) {
            std.log.err("gen_client --check: '{s}' is STALE — re-run gen-client to regenerate.", .{out_path});
            return error.Stale;
        }
        return;
    }

    // Ensure the output directory exists.
    // Zig 0.16: std.Io.Dir.cwd().createDirPath(io, dir) — NOT makePath.
    if (std.fs.path.dirname(out_path)) |dir| {
        std.Io.Dir.cwd().createDirPath(io, dir) catch {};
    }
    // Zig 0.16 file-write: std.Io.Dir.cwd().writeFile(io, .{ .sub_path = path, .data = bytes })
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = out_path, .data = text });
    std.log.info("gen_client: wrote {s} ({d} bytes)", .{ out_path, text.len });
}

/// Legacy entry point kept for back-compat; reads @import("app").App.collections.
/// Prefer mainWithCollections when building as a separate module to avoid
/// the Zig 0.16 "file exists in multiple modules" error (see note above).
pub fn main(init: std.process.Init) !void {
    const app = @import("app");
    return mainWithCollections(init, app.App.collections, app.App.routes, app.App.custom_auth, app.App.flags, app.App.experiments);
}


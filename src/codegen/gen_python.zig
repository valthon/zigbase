}

test "Python keywords are sanitized (wire keys unchanged)" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const cols = [_]schema.Collection{
        .{ .id = "", .name = "users", .type = .auth, .fields = &.{} },
        // `class`/`import` are Python keywords; `expand` collides with the
        // generated record member; select value `class` is a keyword-derived
        // enum member (sanitized only after the uppercase transform, which
        // never itself collides — this exercises the general path anyway).
        .{ .id = "", .name = "raw", .fields = &.{
            .{ .id = "", .name = "class", .required = true, .options = .{ .text = .{} } },
            .{ .id = "", .name = "import", .options = .{ .number = .{ .mode = .int } } },
            .{ .id = "", .name = "expand", .options = .{ .text = .{} } },
            .{ .id = "", .name = "author", .options = .{ .relation = .{ .targetCollectionId = "users", .maxSelect = 1 } } },
        } },
    };
    const out = try generate(a, &cols, &.{}, &.{}, &.{}, &.{}, true, "users", "ZbClient", "/api");
    // Record members: keyword-sanitized Python identifier, wire key untouched.
    try std.testing.expect(std.mem.indexOf(u8, out, "class_: str") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "import_: int") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "expand_: str") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "class_=zbt.coerce_str(r.get(\"class\")),") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "import_=zbt.coerce_int(r.get(\"import\")),") != null);
    // No unsanitized keyword member leaked.
    try std.testing.expect(std.mem.indexOf(u8, out, "class: str") == null);
    try std.testing.expect(std.mem.indexOf(u8, out, "import: int") == null);
    // Payload: required field + to_map keeps the wire key.
    try std.testing.expect(std.mem.indexOf(u8, out, "class_: str\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "m[\"class\"] = self.class_") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "m[\"import\"] = zbt.encode_int(self.import_)") != null);
}


//! Pure-Zig Python client generator: collections -> a zbase_gen.py that
//! instantiates the runtime in clients/python/src/zigbase/typed.py (imported
//! as `zbt`) into concrete pydantic BaseModel classes, fluent field builders,
//! per-collection metadata, sync/async typed services, realtime subclasses,
//! and the `ZbClient`/`AsyncZbClient` façades. The Python counterpart of
//! gen_dart.generate; shares the acquisition layer and the guard bar
//! (guards.checkIdentifiers), and branches only in emission. NB: that guard bar
//! is TS-derived (TS identifier validity + the TS typed-core reserved-name set),
//! applied to every language as a conservative lowest common denominator — NOT a
//! language-neutral check. The Python-specific keyword/member sanitizing that
//! keeps THIS output legal lives in emit_python.zig.
const std = @import("std");
const schema = @import("../schema.zig");
const events = @import("../events.zig");
const features = @import("../features.zig");
const emit = @import("emit_python.zig");
const guards = @import("guards.zig");
const ident = @import("identifiers.zig");
const gen_client = @import("gen_client.zig");

const W = std.ArrayList(u8);

/// The `zigbase.typed.TYPED_CORE_VERSION` value this emitter targets — a
/// human/tooling compatibility marker in the generated header, matching the
/// literal in clients/python/src/zigbase/typed.py. Not read across the
/// language boundary at build time; keep the two in sync by hand.
const TYPED_CORE_VERSION = "0.1.0";

fn section(alloc: std.mem.Allocator, w: *W, title: []const u8) !void {
    const line = try std.fmt.allocPrint(alloc, "\n# ---- {s} " ++ ("-" ** 4) ++ "\n\n", .{title});
    try w.appendSlice(alloc, line);
}

/// The pure Python generator core: collections -> full file text.
///
/// Signature mirrors gen_dart.generate/gen_client.generate so the CLI/build
/// threading is uniform. `routes`, `custom_auth`, `flags`, `experiments`
/// (the comptime-only surfaces) are accepted for parity but not yet emitted
/// in Python — a documented follow-up, same as Dart. `in_repo` is unused
/// (the snapshot lives inside the client package, so the package import works).
pub fn generate(
    alloc: std.mem.Allocator,
    cols: []const schema.Collection,
    comptime routes: []const events.RouteMeta,
    comptime custom_auth: []const events.CustomAuthMeta,
    flags: []const features.FlagDef,
    experiments: []const features.ExperimentDef,
    in_repo: bool,
    auth_collection: []const u8,
    client_name: []const u8,
    api_prefix: []const u8,
) ![]const u8 {
    _ = routes;
    _ = custom_auth;
    _ = flags;
    _ = experiments;
    _ = in_repo;
    _ = api_prefix;

    var report = guards.GuardReport{ .message = "" };
    try guards.checkOperatorNames(alloc, cols, &report);
    try guards.checkIdentifiers(alloc, cols, &report);

    const needs_enum = emit.anySelectFields(cols);
    const needs_file = emit.anyFileFields(cols);
    const needs_auth = emit.anyAuthCollections(cols);

    var w: W = .empty;
    try w.appendSlice(alloc, try std.fmt.allocPrint(alloc,
        \\# GENERATED by zigbase — do not edit.
        \\# schema-hash: {x:0>16}
        \\# typed-core-version: {s}
        \\#
        \\# A thin, schema-aware wrapper over the base Python SDK's generic typed
        \\# runtime (zigbase.typed, imported below as `zbt`). Regenerate with your
        \\# server's `typegen --lang python` command (or the build-time comptime
        \\# gen-client build step), then `ruff format` it with your project's config.
        \\#
        \\# Identifier mapping: a schema name that is a Python keyword gets a
        \\# trailing `_` on the PYTHON side only (field `class` -> member
        \\# `class_`); wire keys are unchanged.
        \\# ruff: noqa
        \\from __future__ import annotations
        \\
        \\from collections.abc import AsyncIterator, Callable, Iterator, Mapping, Sequence
        \\
    , .{ gen_client.schemaHash(cols), TYPED_CORE_VERSION }));
    if (needs_enum) try w.appendSlice(alloc, "from enum import Enum\n");
    try w.appendSlice(alloc, "from typing import Any\n\nimport zigbase.typed as zbt\n");
    if (needs_auth) {
        try w.appendSlice(alloc, "from zigbase import AsyncZigBase, AuthResponse, AuthStore, ZigBase\n");
    } else {
        try w.appendSlice(alloc, "from zigbase import AsyncZigBase, AuthStore, ZigBase\n");
    }
    if (needs_file) {
        try w.appendSlice(alloc, "from pydantic import BaseModel, ConfigDict\n");
        try w.appendSlice(alloc, "\nfrom zigbase._multipart import FileArg\n");
    } else {
        try w.appendSlice(alloc, "from pydantic import BaseModel\n");
    }

    try section(alloc, &w, "Records");
    for (cols) |c| try emit.emitSelectEnums(alloc, &w, c);
    for (cols) |c| try emit.emitRecord(alloc, &w, cols, c);

    try section(alloc, &w, "Create / Update payloads");
    for (cols) |c| {
        try emit.emitCreate(alloc, &w, c);
        try emit.emitUpdate(alloc, &w, c);
    }

    try section(alloc, &w, "Fluent field builders");
    for (cols) |c| try emit.emitFields(alloc, &w, cols, c);

    try section(alloc, &w, "Per-collection metadata");
    for (cols) |c| try emit.emitMeta(alloc, &w, c);

    try section(alloc, &w, "Typed services");
    for (cols) |c| {
        try emit.emitService(alloc, &w, cols, c);
        try emit.emitAsyncService(alloc, &w, cols, c);
    }

    try section(alloc, &w, "Typed realtime");
    for (cols) |c| try emit.emitRealtime(alloc, &w, c);

    try section(alloc, &w, "Client");
    try emit.emitClient(alloc, &w, cols, client_name, auth_collection);
    try emit.emitAsyncClient(alloc, &w, cols, client_name, auth_collection);

    return w.toOwnedSlice(alloc);
}

test "generate emits a valid-looking Python client for a mini blog" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const cols = [_]schema.Collection{
        .{ .id = "", .name = "users", .type = .auth, .fields = &.{
            .{ .id = "", .name = "displayName", .options = .{ .text = .{} } },
        } },
        .{ .id = "", .name = "posts", .fields = &.{
            .{ .id = "", .name = "title", .required = true, .options = .{ .text = .{} } },
            .{ .id = "", .name = "status", .options = .{ .select = .{ .values = &.{ "draft", "published" }, .maxSelect = 1 } } },
            .{ .id = "", .name = "views", .options = .{ .number = .{ .mode = .int } } },
            .{ .id = "", .name = "author", .options = .{ .relation = .{ .targetCollectionId = "users", .maxSelect = 1 } } },
            .{ .id = "", .name = "cover", .options = .{ .file = .{ .maxSelect = 1 } } },
        } },
    };
    const out = try generate(a, &cols, &.{}, &.{}, &.{}, &.{}, true, "users", "ZbClient", "/api");

    // Byte-exact fragment: the enum class in full (Step 1's "byte-exact

test "select values differing only in case collide into one Python enum member — a generation error" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    // "active" and "ACTIVE" both uppercase to the enum member ACTIVE — the
    // second would silently overwrite the first's `= "active"` line with
    // `= "ACTIVE"` if generation didn't dedup-check before emitting.
    const cols = [_]schema.Collection{
        .{ .id = "", .name = "posts", .fields = &.{
            .{ .id = "", .name = "status", .options = .{ .select = .{ .values = &.{ "active", "ACTIVE" }, .maxSelect = 1 } } },
        } },
    };
    try std.testing.expectError(
        error.PythonIdentCollision,
        generate(a, &cols, &.{}, &.{}, &.{}, &.{}, true, "", "ZbClient", "/api"),
    );
}

test "file_url's Mapping branch uses .get() so an unrequested file field's key may be absent" {
    // No fixture collection in the repo (dating, blog, golfsim) has two
    // single-value file fields, so the golden-based Python behavior tests
    // can't exercise a Mapping missing one file field's key while carrying
    // another's -- this synthetic two-file-field collection is the only
    // place that shape is covered. Regression guard for the KeyError bug: a
    // dict literal's entries are all evaluated eagerly, so bracket-indexing
    // (`record["thumbnail"]`) would raise KeyError building the `filename =
    // {...}` dict for a caller's Mapping that only carries `cover` (e.g. a
    // partial realtime payload), even though only `cover` is ever selected
    // via `[field]`.
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const cols = [_]schema.Collection{
        .{ .id = "", .name = "posts", .fields = &.{
            .{ .id = "", .name = "cover", .options = .{ .file = .{ .maxSelect = 1 } } },
            .{ .id = "", .name = "thumbnail", .options = .{ .file = .{ .maxSelect = 1 } } },
        } },
    };
    const out = try generate(a, &cols, &.{}, &.{}, &.{}, &.{}, true, "", "ZbClient", "/api");

    try std.testing.expect(std.mem.indexOf(u8, out, "class PostFileField(Enum):") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "    COVER = \"cover\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "    THUMBNAIL = \"thumbnail\"") != null);
    try std.testing.expect(std.mem.indexOf(
        u8,
        out,
        "            PostFileField.COVER: record.get(\"cover\") if isinstance(record, Mapping) else record.cover,\n",
    ) != null);
    try std.testing.expect(std.mem.indexOf(
        u8,
        out,
        "            PostFileField.THUMBNAIL: record.get(\"thumbnail\") if isinstance(record, Mapping) else record.thumbnail,\n",
    ) != null);
    // No bracket-indexed lookup anywhere in the filename dict (that's the
    // KeyError-on-partial-Mapping bug this test guards against).
    try std.testing.expect(std.mem.indexOf(u8, out, "record[\"cover\"]") == null);
    try std.testing.expect(std.mem.indexOf(u8, out, "record[\"thumbnail\"]") == null);
}


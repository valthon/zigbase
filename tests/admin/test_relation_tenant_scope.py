def _raw(base, method, path, body, client, headers=None):
    """A JSON write returning (status, raw body bytes): bodies are compared byte for byte."""
    token, default_headers = client
    hdrs = {**(default_headers if headers is None else headers), "Authorization": f"Bearer {token}",
            "Content-Type": "application/json"}
    req = urllib.request.Request(base + path, data=json.dumps(body).encode(), headers=hdrs, method=method)
    try:
        response = urllib.request.urlopen(req, timeout=10)
    except urllib.error.HTTPError as error:
        response = error
    with response:
        return response.status, response.read()


def _not_found(result, field):
    assert result[0] == 400, result
    assert json.loads(result[1])["data"][field]["code"] == "validation_not_found", result


def _setup(base, data_dir, extra_memberships=()):
    """Two profiles, A in acct-a and B in acct-b (plus any `(name, account)` in
    `extra_memberships`); `rc_tasks` (single + multi relation to the tenant-owned `notes`) and
    `rc_items` (cascadeDelete relation to `notes`), both tenant-owned; `rc_links`, a relation to
    `notes` from a collection that is NOT tenant-owned. Returns (admin token, {name: (token, headers)})."""
    code, login = call(base, "POST", "/api/collections/_superusers/auth-with-password",
                       {"identity": "admin@x.io", "password": "adminpassword"})
    assert code == 200, login
    admin = login["token"]
    users = {}
    for name in ("a", "b"):
        email = f"{name}@example.com"
        code, rec = call(base, "POST", "/api/collections/profiles/records",
                         {"email": email, "password": "password12345", "passwordConfirm": "password12345", "name": name}, admin)
        assert code == 201, rec
        users[name] = rec["id"]
    with sqlite3.connect(data_dir / "data.db") as db:
        for name, uid in users.items():
            account = "acct-" + name
            db.execute("INSERT INTO _accounts(id,created,updated,slug) VALUES(?,?,?,?)", (account, "2026-01-01", "2026-01-01", account))
            db.execute("INSERT INTO _memberships(id,created,updated,account,user_collection,user,role,status) VALUES(?,?,?,?,?,?,?,?)",
                       ("member-" + name, "2026-01-01", "2026-01-01", account, "profiles", uid, "owner", "active"))
        for name, account in extra_memberships:
            db.execute("INSERT INTO _memberships(id,created,updated,account,user_collection,user,role,status) VALUES(?,?,?,?,?,?,?,?)",
                       (f"member-{name}-{account}", "2026-01-01", "2026-01-01", account, "profiles", users[name], "editor", "active"))
    clients = {}
    for name in ("a", "b"):
        code, login = call(base, "POST", "/api/collections/profiles/auth-with-password",
                           {"identity": f"{name}@example.com", "password": "password12345"})
        assert code == 200, login
        clients[name] = (login["token"], {"X-Account-Id": "acct-" + name})
    code, notes = call(base, "GET", "/api/collections/notes", token=admin)
    assert code == 200, notes
    rules = {k: ANY_AUTH for k in ("listRule", "viewRule", "createRule", "updateRule", "deleteRule")}
    text = lambda n: {"id": "", "name": n, "type": "text", "options": {}}
    rel = lambda n, max_select, cascade: {"id": "", "name": n, "type": "relation",
                                          "options": {"targetCollectionId": notes["id"], "maxSelect": max_select, "cascadeDelete": cascade}}
    for body in (
        {"name": "rc_tasks", "fields": [text("title"), text("account"), rel("note", 1, False), rel("notes", 5, False)]},
        {"name": "rc_items", "fields": [text("title"), text("account"), rel("note", 1, True)]},
    ):
        code, col = call(base, "POST", "/api/collections",
                         {**body, "type": "base", **rules, "options": {"tenant": {"field": "account"}}}, admin)
        assert code == 201, col
    code, col = call(base, "POST", "/api/collections",
                     {"name": "rc_links", "fields": [text("title"), rel("note", 1, False)], "type": "base", **rules}, admin)
    assert code == 201, col
    return admin, clients


def _create(base, client, collection, body, headers=None):
    return _raw(base, "POST", f"/api/collections/{collection}/records", body, client, headers)


def _patch(base, client, collection, rid, body):
    return _raw(base, "PATCH", f"/api/collections/{collection}/records/{rid}", body, client)


def _note(base, client, title, headers=None):
    code, rec = _create(base, client, "notes", {"title": title}, headers)
    assert code == 201, rec
    return json.loads(rec)["id"]


def test_foreign_tenant_relation_id_answers_like_a_never_minted_one(app):
    base, data_dir, _ = app
    _, clients = _setup(base, data_dir)
    a, b = clients["a"], clients["b"]
    foreign = _note(base, b, "b-private")
    own = _note(base, a, "a-own")

    # Create, single relation: same status AND byte-identical body for foreign vs never-minted.
    as_foreign = _create(base, a, "rc_tasks", {"title": "t", "note": foreign})
    as_missing = _create(base, a, "rc_tasks", {"title": "t", "note": NEVER_MINTED})
    _not_found(as_foreign, "note")
    assert as_foreign == as_missing

    # Create, multi relation.
    multi_foreign = _create(base, a, "rc_tasks", {"title": "t", "notes": [own, foreign]})
    multi_missing = _create(base, a, "rc_tasks", {"title": "t", "notes": [own, NEVER_MINTED]})
    assert multi_foreign[0] == 400 and multi_foreign == multi_missing, (multi_foreign, multi_missing)

    # Update (PATCH of A's own task), single and multi.
    code, task = _create(base, a, "rc_tasks", {"title": "t", "note": own, "notes": [own]})
    assert code == 201, task
    task = json.loads(task)
    for field, foreign_value, missing_value in (("note", foreign, NEVER_MINTED),
                                                ("notes", [own, foreign], [own, NEVER_MINTED])):
        upd_foreign = _patch(base, a, "rc_tasks", task["id"], {field: foreign_value})
        upd_missing = _patch(base, a, "rc_tasks", task["id"], {field: missing_value})
        assert upd_foreign[0] == 400 and upd_foreign == upd_missing, (upd_foreign, upd_missing)

    # Nothing was stored: A's task still points at its own note only.
    code, stored = call(base, "GET", f"/api/collections/rc_tasks/records/{task['id']}", token=a[0], headers=a[1])
    assert code == 200 and stored["note"] == own and stored["notes"] == [own], stored


def test_other_tenant_cannot_link_so_owner_delete_leaves_its_rows_alone(app):
    base, data_dir, _ = app
    _, clients = _setup(base, data_dir)
    a, b = clients["a"], clients["b"]
    a_note = _note(base, a, "a-note")
    b_note = _note(base, b, "b-note")

    # B cannot point its rows at A's note (the link the cascade would follow) ...
    for collection in ("rc_items", "rc_tasks"):
        _not_found(_create(base, b, collection, {"title": "b row", "note": a_note}), "note")
    # ... while its own note links fine.
    for collection in ("rc_items", "rc_tasks"):
        code, body = _create(base, b, collection, {"title": "b row", "note": b_note})
        assert code == 201, (collection, body)

    code, _ = call(base, "DELETE", f"/api/collections/notes/records/{a_note}", token=a[0], headers=a[1])
    assert code == 204

    for collection in ("rc_items", "rc_tasks"):
        code, page = call(base, "GET", f"/api/collections/{collection}/records?fields=title,note", token=b[0], headers=b[1])
        assert code == 200, page
        assert page["items"] == [{"title": "b row", "note": b_note}], (collection, page)


def test_superuser_can_still_link_across_tenants_and_doctor_reports_it(app):
    base, data_dir, binary = app
    admin, clients = _setup(base, data_dir)
    a_note = _note(base, clients["a"], "a-note")

    code, rec = call(base, "POST", "/api/collections/rc_tasks/records",
                     {"title": "su link", "account": "acct-b", "note": a_note}, admin)
    assert code == 201 and rec["note"] == a_note, rec

    env = {k: v for k, v in os.environ.items() if not k.startswith("ZIGBASE_")}
    env["ZIGBASE_FAKE_HASH"] = "1"
    doctor = subprocess.run([binary, "doctor", "--json", "--data-dir", str(data_dir)], env=env,
                            capture_output=True, text=True, timeout=60)
    lines = [json.loads(line) for line in doctor.stdout.splitlines() if line.startswith("{")]
    findings = [line for line in lines if line.get("check") == "cross-tenant-relations"]
    assert findings == [{
        "check": "cross-tenant-relations", "severity": "warn", "subject": "rc_tasks.note",
        "message": findings[0]["message"] if findings else None,
    }], doctor.stdout + doctor.stderr
    assert "1 stored link(s)" in findings[0]["message"]


def _doctor(binary, data_dir):
    env = {k: v for k, v in os.environ.items() if not k.startswith("ZIGBASE_")}
    env["ZIGBASE_FAKE_HASH"] = "1"
    run = subprocess.run([binary, "doctor", "--json", "--data-dir", str(data_dir)], env=env,
                         capture_output=True, text=True, timeout=60)
    return [json.loads(line) for line in run.stdout.splitlines() if line.startswith("{")], run


def test_non_tenant_source_is_scoped_too_and_no_active_account_fails_closed(app):
    base, data_dir, _ = app
    _, clients = _setup(base, data_dir)
    a, b = clients["a"], clients["b"]
    foreign = _note(base, b, "b-private")
    own = _note(base, a, "a-own")

    # `rc_links` is not tenant-owned; its relation into the tenant-owned `notes` is still scoped.
    as_foreign = _create(base, a, "rc_links", {"title": "l", "note": foreign})
    _not_found(as_foreign, "note")
    assert as_foreign == _create(base, a, "rc_links", {"title": "l", "note": NEVER_MINTED})
    code, body = _create(base, a, "rc_links", {"title": "l", "note": own})
    assert code == 201, body

    # Without X-Account-Id there is no active account: even A's own note is out of scope.
    _not_found(_create(base, a, "rc_links", {"title": "l", "note": own}, headers={}), "note")


def test_a_member_of_two_accounts_links_within_the_header_selected_one(app):
    base, data_dir, _ = app
    _, clients = _setup(base, data_dir, extra_memberships=[("a", "acct-b")])
    a = clients["a"]
    in_b = {"X-Account-Id": "acct-b"}
    b_note = _note(base, a, "made in acct-b", headers=in_b)

    # Active account acct-a: the acct-b note is another account's record.
    _not_found(_create(base, a, "rc_tasks", {"title": "t", "note": b_note}), "note")
    # Switching the header to acct-b makes the same id the active account's own.
    code, body = _create(base, a, "rc_tasks", {"title": "t", "note": b_note}, headers=in_b)
    assert code == 201 and json.loads(body)["note"] == b_note, body


@pytest.mark.parametrize("view_rule", [ANY_AUTH, '@request.method = "GET" && @request.data.title = ""'])
def test_resending_a_stored_cross_tenant_link_is_accepted_but_a_new_one_is_not(app, view_rule):
    base, data_dir, _ = app
    admin, clients = _setup(base, data_dir)
    a, b = clients["a"], clients["b"]
    a_note = _note(base, a, "a-note")
    b_note = _note(base, b, "b-note")
    b_note2 = _note(base, b, "b-note-2")

    # A legacy link: a superuser stored acct-a's task pointing at acct-b's note.
    code, task = call(base, "POST", "/api/collections/rc_tasks/records",
                      {"title": "legacy", "account": "acct-a", "note": b_note, "notes": [a_note, b_note]}, admin)
    assert code == 201, task

    code, col = call(base, "GET", "/api/collections/rc_tasks", token=admin)
    assert code == 200, col
    code, body = call(base, "PATCH", "/api/collections/rc_tasks",
                      {**col, "fields": col["schema"], "viewRule": view_rule}, admin)
    assert code == 200, body

    # A re-sends the whole record it reads back (an SDK save): accepted, the link is unchanged.
    code, stored = call(base, "GET", f"/api/collections/rc_tasks/records/{task['id']}", token=a[0], headers=a[1])
    assert code == 200, stored
    resend = {k: stored[k] for k in ("title", "note", "notes")}
    code, body = _patch(base, a, "rc_tasks", task["id"], {**resend, "title": "renamed"})
    assert code == 200, body
    assert json.loads(body)["notes"] == [a_note, b_note]

    # Adding a NEW foreign id next to the kept ones, or switching the single link to one, is refused.
    _not_found(_patch(base, a, "rc_tasks", task["id"], {"notes": [a_note, b_note, b_note2]}), "notes")
    _not_found(_patch(base, a, "rc_tasks", task["id"], {"note": b_note2}), "note")


def test_doctor_scan_failure_skips_only_its_own_check(app):
    base, data_dir, binary = app
    _setup(base, data_dir)
    # Make the cross-tenant scan fail on a database every other check can still read.
    with sqlite3.connect(data_dir / "data.db") as db:
        db.execute("DROP TABLE rc_items")
    findings, run = _doctor(binary, data_dir)
    by_check = {}
    for line in findings:
        if "check" in line:
            by_check.setdefault(line["check"], []).append(line)
    ct = by_check["cross-tenant-relations"]
    assert [f["severity"] for f in ct] == ["skipped"], run.stdout + run.stderr
    assert "could not scan relation links" in ct[0]["message"], ct
    for other in ("public-rules-enumerated", "migrations-applied", "legacy-password-hashes"):
        for f in by_check[other]:
            assert f["severity"] != "skipped" and "unreachable" not in f["message"], (other, f)


@pytest.mark.parametrize("field,multi", [("note", False), ("notes", True)])
def test_hidden_stored_foreign_relation_is_not_an_existence_oracle(app, field, multi):
    base, data_dir, _ = app
    admin, clients = _setup(base, data_dir)
    a, b = clients["a"], clients["b"]
    foreign = _note(base, b, "hidden legacy")
    another = _note(base, b, "another foreign")
    own = _note(base, a, "own")
    code, col = call(base, "GET", "/api/collections/rc_tasks", token=admin)
    assert code == 200, col
    for f in col["schema"]:
        if f["name"] == field:
            f["hidden"] = True
    code, body = call(base, "PATCH", "/api/collections/rc_tasks", {**col, "fields": col["schema"]}, admin)
    assert code == 200, body
    value = lambda rid: [rid] if multi else rid
    code, task = call(base, "POST", "/api/collections/rc_tasks/records",
                      {"account": "acct-a", field: value(foreign)}, admin)
    assert code == 201, task
    code, visible = call(base, "GET", f"/api/collections/rc_tasks/records/{task['id']}",
                         token=a[0], headers=a[1])
    assert code == 200 and field not in visible, visible
    guessed = _patch(base, a, "rc_tasks", task["id"], {field: value(foreign)})
    _not_found(guessed, field)
    assert guessed == _patch(base, a, "rc_tasks", task["id"], {field: value(another)})
    assert guessed == _patch(base, a, "rc_tasks", task["id"], {field: value(NEVER_MINTED)})
    # Hidden fields remain writable when the new target is actually in scope.
    assert _patch(base, a, "rc_tasks", task["id"], {field: value(own)})[0] == 200


def test_no_active_account_cannot_link_an_empty_owner_target(app):
    base, data_dir, _ = app
    admin, clients = _setup(base, data_dir)
    a = clients["a"]
    note = {"id": _note(base, a, "imported unowned")}
    # Import a legacy target owned by no account (the account relation normally rejects "").
    with sqlite3.connect(data_dir / "data.db") as db:
        db.execute("UPDATE notes SET account='' WHERE id=?", (note["id"],))
    no_account = (a[0], {})
    result = _create(base, no_account, "rc_links", {"note": note["id"]})
    _not_found(result, "note")
    assert result == _create(base, no_account, "rc_links", {"note": NEVER_MINTED})
    code, link = _create(base, no_account, "rc_links", {"title": "no relation"})
    assert code == 201, link
    rid = json.loads(link)["id"]
    result = _patch(base, no_account, "rc_links", rid, {"note": note["id"]})
    _not_found(result, "note")
    assert result == _patch(base, no_account, "rc_links", rid, {"note": NEVER_MINTED})
    # Privileged writes and resending a visible stored link still work without an account.
    code, legacy = call(base, "POST", "/api/collections/rc_links/records", {"note": note["id"]}, admin)
    assert code == 201, legacy
    assert _patch(base, no_account, "rc_links", legacy["id"], {"note": note["id"]})[0] == 200


@pytest.mark.parametrize("field,multi", [("note", False), ("notes", True)])
@pytest.mark.parametrize("view_rule", [None, 'title = "readable"',
                                      '@request.method = "GET" && @request.data.title = "grant"'])
def test_unreadable_source_stored_relation_is_not_an_existence_oracle(app, field, multi, view_rule):
    base, data_dir, _ = app
    admin, clients = _setup(base, data_dir)
    a, b = clients["a"], clients["b"]
    foreign = _note(base, b, "legacy")
    another = _note(base, b, "another")
    value = lambda rid: [rid] if multi else rid
    code, task = call(base, "POST", "/api/collections/rc_tasks/records",
                      {"title": "private", "account": "acct-a", field: value(foreign)}, admin)
    assert code == 201, task
    code, col = call(base, "GET", "/api/collections/rc_tasks", token=admin)
    assert code == 200, col
    code, body = call(base, "PATCH", "/api/collections/rc_tasks",
                      {**col, "fields": col["schema"], "viewRule": view_rule,
                       "updateRule": 'title = "updatable"'}, admin)
    assert code == 200, body
    code, body = call(base, "GET", f"/api/collections/rc_tasks/records/{task['id']}",
                      token=a[0], headers=a[1])
    assert code == 404, body
    # A guessed stored id must fail validation just like every other out-of-scope id,
    # before the expression-based update guard. PATCH data must not grant GET access.
    guessed = _patch(base, a, "rc_tasks", task["id"], {field: value(foreign), "title": "grant"})
    _not_found(guessed, field)
    for rid in (another, NEVER_MINTED):
        assert guessed == _patch(base, a, "rc_tasks", task["id"], {field: value(rid), "title": "grant"})

@pytest.mark.parametrize(
    ("grade_name", "mutation"),
    [
        ("completion", "missing_report"),
        ("rules_locked", "unreviewed_public"),
        ("tests_green", "failed_boundary"),
        ("deployed", "failed_restore"),
    ],
)
def test_one_isolated_failure_per_grade(tmp_path, grade_name, mutation):
    target = workspace(tmp_path)
    commands = FakeCommands(fail={"failed_boundary": "unittest"}.get(mutation))
    extra = {}
    if mutation == "failed_restore":
        # The restored copy boots but does not serve the migration.
        def refuse(*_args, **_kwargs):
            from evals.agents.graders.genesis import GradeFailure

            raise GradeFailure(
                "deployment.restored_login", "the migrated credential did not log in"
            )

        extra["restore_probe"] = refuse
    if mutation == "missing_report":
        (target / "migration" / "report.json").unlink()
    elif mutation == "unreviewed_public":
        # The TARGET grants something the review never covered. Editing the bundle
        # instead would break its recorded hashes and flip `completion`, which is a
        # different finding — this grade has to be able to fail on its own.
        commands = FakeCommands(
            doctor="\n".join(
                json.dumps(line)
                for line in (
                    {
                        "check": "public-rules-enumerated",
                        "severity": "warn",
                        "subject": "users.createRule",
                        "message": "reviewed public rule",
                    },
                    {
                        "check": "public-rules-enumerated",
                        "severity": "warn",
                        "subject": "posts.listRule",
                        "message": "NOT in the reviewed inventory",
                    },
                    {
                        "summary": True,
                        "production": True,
                        "checks": 9,
                        "errors": 0,
                        "warnings": 2,
                        "skipped": 0,
                    },
                )
            )
        )
    report = grade_fixture(target, tmp_path / "artifacts", commands, **extra)
    assert getattr(report, grade_name) is False
    # Isolated means isolated: the other three must survive, or this fixture is not
    # demonstrating that the grades are independent.
    others = {"completion", "rules_locked", "tests_green", "deployed"} - {grade_name}
    still_true = {name: getattr(report, name) for name in sorted(others)}
    assert all(still_true.values()), (
        f"{mutation} moved more than {grade_name}: {still_true}"
    )



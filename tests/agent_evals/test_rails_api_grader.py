def test_scenario_source_and_converter_are_exact_pinned_copies():
    """A fixture copy that drifts grades an agent against a tool nobody ships.

    Same guard the pocketbase scenario carries for `pb2zb.py`, extended to the frozen
    snapshot: the eval must run the committed converter over the committed fixture.
    """
    for name in ("__init__.py", "_core.py", "rails2zb.py"):
        pinned = (SCENARIO / "fixture" / "tools" / "rails" / name).read_bytes()
        assert pinned == (REPO / "tools" / "rails" / name).read_bytes(), name
        assert (FIXTURE / "tools" / "rails" / name).read_bytes() == pinned, name

    def tracked(root):
        # Sidecars are created by reading the database and are gitignored; `.gitignore`
        # itself is per-copy scaffolding, not snapshot content.
        return {
            path.relative_to(root)
            for path in root.rglob("*")
            if path.is_file()
            and path.name != ".gitignore"
            and not path.name.endswith(("-wal", "-shm"))
        }

    frozen = REPO / "tests" / "rails" / "fixtures" / "rails-8.1.3.1"
    # BOTH copies, and BOTH directions. The scenario's snapshot is what an agent
    # migrates; the positive workspace's is what every test here grades against. A
    # one-directional check would miss a file added to a copy, which is exactly how a
    # fixture starts meaning something different from the one it was cloned from.
    for label, copy in (
        ("scenario", SCENARIO / "fixture" / "source"),
        ("positive workspace", FIXTURE / "source"),
    ):
        expected, actual = tracked(frozen), tracked(copy)
        assert expected == actual, (
            f"the {label} snapshot no longer holds the same files as the frozen "
            f"fixture: missing={sorted(map(str, expected - actual))[:3]} "
            f"extra={sorted(map(str, actual - expected))[:3]}"
        )
        for relative in sorted(expected):
            assert (copy / relative).read_bytes() == (frozen / relative).read_bytes(), (
                f"the {label} snapshot has drifted at {relative}"
            )


def test_prompt_states_the_boundaries_the_grader_enforces():
    """The prompt and the grader must agree, or the scenario is unpassable by design.

    A grader that demands something the prompt never asked for is not measuring the
    agent; it is measuring whether the agent guessed.
    """
    prompt = " ".join((SCENARIO / "prompt.md").read_text().lower().split())
    assert "leave `source/` byte-for-byte unchanged" in prompt
    assert "zigbaserailsmigrationreport" in prompt
    for check in ("scope", "determinism", "rehash", "restore"):
        assert f'"{check}"' in prompt, f"the prompt never asks for the {check} check"
    # The two semantics the grader probes and an agent most often gets backwards.
    assert "empty `items` array" in prompt
    assert "concealed as `404`" in prompt
    # The scope gate, which is the whole reason this scenario is `-rails-api`.
    assert "not migrated" in prompt or "never" in prompt
    assert '"users.create"' in prompt



def test_a_thin_rationale_is_not_a_decision(tmp_path):
    """Recording a choice without saying why is how a migration loses its audit trail."""
    target = workspace(tmp_path)
    path = target / "decisions.json"
    value = json.loads(path.read_text())
    value["decisions"][0]["rationale"] = "ok"
    path.write_text(json.dumps(value))
    _, failures = inspect_completion(target)
    assert any(f.code == "completion.rationales" for f in failures)

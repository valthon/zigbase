"""The rails-api grader, against a workspace a competent agent would leave behind.

The committed fixture is the POSITIVE case, generated by running the real converter
rather than hand-written, so it cannot drift from what the tool emits. Every failure
case is derived from it here by breaking exactly one thing — which is also the argument
that each grade can fail on its own rather than all four moving together.

No binary, server or network is needed: every command the grader shells out to is
injected, and the live probes are replaced. What is exercised is the grader's judgement,
not ZigBase's.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

from evals.agents.graders.genesis import CommandResult
from evals.agents.graders.rails_api import (
    EXPECTED_PUBLIC,
    grade,
    inspect_completion,
    load_reviewed_public_inventory,
)
from evals.agents.scenario import AgentScenario

REPO = Path(__file__).resolve().parents[2]
FIXTURE = REPO / "tests" / "agent_evals" / "fixtures" / "rails-api" / "positive"
SCENARIO = REPO / "evals" / "agents" / "scenarios" / "rails-api"

#: What `doctor --production --json` emits for this migration: one reviewed public
#: rule as a WARNING, which the guide says to reconcile rather than suppress.
DOCTOR = "\n".join(
    json.dumps(line)
    for line in (
        {
            "check": "public-rules-enumerated",
            "severity": "warn",
            "subject": "users.createRule",
            "message": "reviewed public rule",
        },
        {
            "summary": True,
            "production": True,
            "checks": 9,
            "errors": 0,
            "warnings": 1,
            "skipped": 0,
        },
    )
)


class FakeCommands:
    """Records what the grader ran, and can be told to fail one step."""

    def __init__(self, *, fail: str | None = None, doctor: str = DOCTOR) -> None:
        self.fail = fail
        self.doctor = doctor
        self.calls: list[list[str]] = []

    def run(self, argv, *, cwd, env=None, timeout=300):  # noqa: ANN001, ARG002
        self.calls.append([str(part) for part in argv])
        joined = " ".join(str(part) for part in argv)
        if self.fail and self.fail in joined:
            return CommandResult(returncode=1, stderr=f"forced failure: {self.fail}")
        if "doctor" in joined:
            return CommandResult(returncode=0, stdout=self.doctor)
        return CommandResult(returncode=0, stdout="")


def workspace(tmp_path: Path) -> Path:
    target = tmp_path / "workspace"
    shutil.copytree(FIXTURE, target)
    return target


def grade_fixture(target: Path, artifacts: Path, commands=None, **kwargs):
    # `schema apply` is faked, so nothing creates the rehearsed target. Stand in the
    # two files the restore insists on finding: a backup that cannot serve, or that
    # leaves `.jwt_secret` behind, is not a rollback unit.
    rehearsed = target / ".rehearsal" / "data"
    rehearsed.mkdir(parents=True, exist_ok=True)
    (rehearsed / "data.db").write_bytes(b"")
    (rehearsed / ".jwt_secret").write_bytes(b"x" * 64)
    kwargs.setdefault("restore_probe", lambda *_a, **_k: None)
    return grade(
        target,
        artifacts,
        commands=commands or FakeCommands(),
        binary_path=str(REPO / "tools" / "rails" / "rails2zb.py"),  # any real file
        port_picker=lambda: 45999,
        behavior_probe=lambda *_a, **_k: None,
        database_inspector=lambda *_a, **_k: None,
        file_installer=lambda *_a, **_k: {"files": 1, "installed": 1, "reused": 0},
        health_getter=lambda *_a, **_k: {"status": "ok"},
        **kwargs,
    )



def test_positive_fixture_scores_four(tmp_path):
    commands = FakeCommands()
    report = grade_fixture(workspace(tmp_path), tmp_path / "artifacts", commands)
    assert report.failures == ()
    assert (
        report.completion,
        report.rules_locked,
        report.tests_green,
        report.deployed,
    ) == (
        True,
        True,
        True,
        True,
    )


def test_the_rehearsal_runs_the_documented_commands_in_order(tmp_path):
    commands = FakeCommands()
    grade_fixture(workspace(tmp_path), tmp_path / "artifacts", commands)
    joined = [" ".join(call) for call in commands.calls]

    def index(fragment: str) -> int:
        return next(i for i, call in enumerate(joined) if fragment in call)

    # Auth is imported separately from ordinary data, and before it: the manifest
    # importer resolves relations against rows the auth file must already have created.
    assert index("--collection users") < index("--manifest")
    assert any("--dry-run" in call for call in joined), "the schema is dry-run first"
    assert any("--preserve-timestamps" in call for call in joined)
    assert any("--legacy-hashes bcrypt" in call for call in joined)
    # Doctor precedes the agent's own boundary, so a failing test cannot take
    # `rules_locked` down with `tests_green`.
    assert index("doctor") < index("unittest")



def test_restored_probe_does_not_regrade_authorization():
    """Deployment proves complete restored bytes and login, not rule policy twice.

    Full restored counts are checked directly from SQLite. Owner scoping belongs to
    ``tests_green``; issuing a scoped read here would make one rule fault sink two grades.
    """

    calls = []

    def request(method, url, *, token=None, body=None):  # noqa: ANN001, ARG001
        calls.append((method, url, token, body))
        return 200, json.dumps({"token": "ada-token"}).encode()

    _probe_restored("http://127.0.0.1:45999", http_request=request)
    assert len(calls) == 1
    assert calls[0][1].endswith("/auth-with-password")


def test_the_rehearsal_runs_the_documented_commands_in_order(tmp_path):
    commands = FakeCommands()
    grade_fixture(workspace(tmp_path), tmp_path / "artifacts", commands)
    joined = [" ".join(call) for call in commands.calls]

    def index(fragment: str) -> int:
        return next(i for i, call in enumerate(joined) if fragment in call)

    # Auth is imported separately from ordinary data, and before it: the manifest
    # importer resolves relations against rows the auth file must already have created.
    assert index("--collection users") < index("--manifest")
    assert any("--dry-run" in call for call in joined), "the schema is dry-run first"
    assert any("--preserve-timestamps" in call for call in joined)
    assert any("--legacy-hashes bcrypt" in call for call in joined)
    # Every trusted live and restored-target probe precedes the mutable agent-authored
    # boundary. Nothing may consume workspace or target state after that test runs.
    assert index("doctor") < index("unittest")
    assert index("unittest") == len(joined) - 1


